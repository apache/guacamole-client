import { TestBed } from '@angular/core/testing';
import { PlayerHeatmapService } from './player-heatmap.service';

/**
 * The height, in pixels, of the heatmaps generated by the tests.
 */
const HEIGHT = 100;

/**
 * The width, in pixels, of the heatmaps generated by the tests.
 */
const WIDTH = 1000;

/**
 * The maximum number of frames per millisecond, as used by the player for the
 * frame heatmap.
 */
const FRAME_RATE_CAP = 10 / 1000;

/**
 * Extracts every number from the given SVG path.
 *
 * @param path
 *     The SVG path to extract the numbers from.
 *
 * @returns
 *     All numbers in the path, in order of appearance, including "NaN" and
 *     "Infinity" if the path contains them.
 */
function numbersIn(path: string): number[] {
    return (path.match(/-?(?:\d+\.?\d*(?:e[-+]?\d+)?|NaN|Infinity)/g) ?? []).map(Number);
}

describe('PlayerHeatmapService', () => {

    let service: PlayerHeatmapService;

    beforeEach(() => {
        service = TestBed.inject(PlayerHeatmapService);
    });

    it('should return an empty path if there are no timestamps', () => {
        expect(service.generateHeatmapPath([], 5000, FRAME_RATE_CAP, HEIGHT, WIDTH)).toBe('');
    });

    it('should return an empty path if the duration is not positive', () => {
        expect(service.generateHeatmapPath([0], 0, FRAME_RATE_CAP, HEIGHT, WIDTH)).toBe('');
    });

    it('should return an empty path if the height or width is missing', () => {
        vi.spyOn(console, 'warn').mockImplementation(() => undefined);
        expect(service.generateHeatmapPath([0], 5000, FRAME_RATE_CAP, 0, WIDTH)).toBe('');
        expect(service.generateHeatmapPath([0], 5000, FRAME_RATE_CAP, HEIGHT, 0)).toBe('');
        vi.restoreAllMocks();
    });

    it('should scale the highest point of a long recording to the full height', () => {

        // Three events in three different 1000 ms buckets stay below the rate
        // cap of 10 events per bucket, so the smoothed peak (0.6827 of the
        // largest bucket) is drawn at 100 - 0.6827 * 100 = 31.73
        const path = service.generateHeatmapPath([20000, 40000, 60000], 100000, FRAME_RATE_CAP, HEIGHT, WIDTH);

        expect(path.startsWith('M0,100L0,100C')).toBe(true);
        expect(numbersIn(path).every(Number.isFinite)).toBe(true);

        const ys = numbersIn(path).filter((_, index) => index % 2 === 1);
        expect(Math.min(...ys)).toBeCloseTo(31.73, 2);
    });

    // A 500 ms recording has buckets of 5 ms, so the rate cap of 10 events per
    // second allows 0.05 events per bucket, which floors to 0
    it('should draw a finite path for a recording so short that the rate cap allows less than one event per bucket', () => {
        const path = service.generateHeatmapPath([100, 200, 300], 500, FRAME_RATE_CAP, HEIGHT, WIDTH);

        expect(path).not.toContain('NaN');
        expect(path).not.toContain('Infinity');
        expect(path.startsWith('M0,100L0,100C')).toBe(true);

        // One event per bucket after capping: the smoothed peak is 0.6827
        // of one event, drawn at 100 - 0.6827 * 100 = 31.73
        const ys = numbersIn(path).filter((_, index) => index % 2 === 1);
        expect(Math.min(...ys)).toBeCloseTo(31.73, 2);
    });

});
